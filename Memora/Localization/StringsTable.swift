/// All UI strings in Arabic (default) and English. One table keeps both languages in
/// sync; `StringsTableTests` verifies that every key has both translations.
enum StringsTable {
    typealias Entry = (ar: String, en: String)

    static let all: [String: Entry] = {
        var table: [String: Entry] = [:]
        for part in [common, enums, study, learn, home, library, importing, analytics, settings, misc] {
            table.merge(part) { first, _ in first }
        }
        return table
    }()

    static func lookup(_ key: String, language: AppLanguage) -> String {
        guard let entry = all[key] else { return key }
        let value = language == .arabic ? entry.ar : entry.en
        return value.isEmpty ? entry.en : value
    }

